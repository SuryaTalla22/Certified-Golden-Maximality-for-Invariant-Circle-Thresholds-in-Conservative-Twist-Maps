def latex_tabular(headers: Sequence[str], rows: Sequence[Sequence[Any]], caption: str, label: str) -> str:
    alignment = "l" * len(headers)
    out = []
    out.append("% AUTO-GENERATED by scripts/generate_manuscript_audit_tables.py")
    out.append("% Source: proof-audit JSON/CSV payloads. Do not edit by hand.")
    out.append(r"\begin{table}[htbp]")
    out.append(r"\centering")
    out.append(r"\small")
    out.append(r"\begin{tabular}{" + alignment + r"}")
    out.append(r"\hline")
    out.append(" & ".join(latex_escape(h) for h in headers) + r" \\")
    out.append(r"\hline")
    for row in rows:
        out.append(" & ".join(latex_escape(cell) for cell in row) + r" \\")
    out.append(r"\hline")
    out.append(r"\end{tabular}")
    out.append(r"\caption{" + latex_escape(caption) + r"}")
    out.append(r"\label{" + latex_escape(label) + r"}")
    out.append(r"\end{table}")
    out.append("")
    return "\n".join(out)


def write_table(path: Path, headers: Sequence[str], rows: Sequence[Sequence[Any]], caption: str, label: str) -> None:
    ensure_parent(path)
    path.write_text(latex_tabular(headers, rows, caption, label), encoding="utf-8")


def build_lower_table(lower: Mapping[str, Any]) -> tuple[list[str], list[list[Any]], str, str]:
    rows: list[list[Any]] = []
    for seg in lower.get("segments", []):
        rows.append([
            seg.get("segment_id", ""),
            f"[{fmt_num(seg.get('K_lo'))}, {fmt_num(seg.get('K_hi'))}]",
            seg.get("N", ""),
            fmt_num(seg.get("radii_margin"), 5),
            fmt_num(seg.get("overlap_with_next"), 5),
            "yes" if seg.get("certified") else "no",
        ])
    rows.append([
        "final anchor",
        f"[{fmt_num(lower.get('final_anchor', [None, None])[0])}, {fmt_num(lower.get('final_anchor', [None, None])[1])}]",
        "--",
        "--",
        "--",
        "reached" if lower.get("final_anchor_reached") else "not reached",
    ])
    return ["segment", "$K$ interval", "$N$", "radii margin", "overlap", "status"], rows, (
        "Lower-corridor proof-audit segments. The final-anchor row is generated from the audit payload and "
        "records the current known lower gap rather than silently promoting the compact replay anchor."
    ), "tab:lower-corridor-audit-segments"


def build_upper_table(upper: Mapping[str, Any]) -> tuple[list[str], list[list[Any]], str, str]:
    ledger = upper.get("ledger", {})
    rows = [
        ["upper obstruction interval", f"[{fmt_num(ledger.get('upper_lo'))}, {fmt_num(ledger.get('upper_hi'))}]", "raw interval"],
        ["analytic barrier interval", f"[{fmt_num(ledger.get('barrier_lo'))}, {fmt_num(ledger.get('barrier_hi'))}]", "raw interval"],
        ["analytic incompatibility margin", fmt_num(upper.get("analytic_incompatibility_margin"), 6), "barrier lower minus upper ceiling"],
        ["upper localization width", fmt_num(ledger.get("upper_width"), 6), "interval width"],
        ["gap minus upper width", fmt_num(upper.get("gap_minus_upper_width"), 6), "derived margin"],
        ["gap/localization ratio", fmt_num(upper.get("gap_to_localization_ratio"), 6), "derived ratio"],
        ["tail denominators", ", ".join(str(x) for x in upper.get("tail_qs", [])), "tail coherence"],
        ["support fraction floor", fmt_num(upper.get("support_fraction_floor"), 4), "support geometry"],
        ["validator failures", len(upper.get("validator_failures", [])), "must be zero"],
    ]
    return ["quantity", "value", "proof role"], rows, (
        "Upper-obstruction margin ledger generated from the Phase-3 proof-audit JSON payload."
    ), "tab:upper-obstruction-margin-ledger"


def build_transport_table(transport: Mapping[str, Any]) -> tuple[list[str], list[list[Any]], str, str]:
    rows: list[list[Any]] = []
    for component in transport.get("components", []):
        rows.append([
            component.get("name", ""),
            fmt_num(component.get("value"), 6),
            component.get("formula", ""),
            ", ".join(component.get("source_fields", [])),
        ])
    rows.extend([
        ["total charged", fmt_num(transport.get("total_charged"), 6), "sum of components", "component ledger"],
        ["available gap", fmt_num(transport.get("available_gap"), 6), "comparison gap", "audit payload"],
        ["remaining margin", fmt_num(transport.get("remaining_margin"), 6), "available gap minus total charged", "derived inequality"],
        ["margin ratio", fmt_num(transport.get("margin_ratio"), 6), "available gap / total charged", "derived ratio"],
    ])
    return ["component", "bound", "formula", "source fields"], rows, (
        "Decomposed transport budget generated from the Phase-4 audit payload."
    ), "tab:transport-budget-audit"


def build_domain_table(domain: Mapping[str, Any]) -> tuple[list[str], list[list[Any]], str, str]:
    counts = domain.get("route_counts", {})
    route_order = ["screened", "ranked", "pruned", "lifecycle", "termination", "omitted", "uncontrolled"]
    rows = [[route, counts.get(f"{route}_count", counts.get(route, 0)), "generated route count"] for route in route_order]
    rows.extend([
        ["total generated", counts.get("generated_record_count", len(domain.get("records", []))), "all generated records"],
        ["failure fields empty", counts.get("failure_fields_empty", domain.get("failure_fields_empty")), "validator condition"],
        ["omitted-tail status", counts.get("omitted_tail_status", domain.get("omitted_tail_status")), "tail-control convention"],
    ])
    return ["route", "count/status", "role"], rows, (
        "Generated arithmetic-domain route counts. The table is generated directly from the Phase-5 domain audit."
    ), "tab:domain-grammar-route-counts"


def build_replay_table(replay: Mapping[str, Any], full_verified: Mapping[str, Any] | None = None) -> tuple[list[str], list[list[Any]], str, str]:
    order = ["minimal", "downstream", "artifact_audit_suite", "heavy_lower", "heavy_upper", "full_verified"]
    rows: list[list[Any]] = []
    for key in order:
        entry = replay.get(key, {})
        rows.append([
            key,
            entry.get("script", ""),
            "yes" if entry.get("heavy_layer") else "no",
            fmt_num(entry.get("runtime_seconds"), 4),
            entry.get("returncode", "not run"),
        ])
    if full_verified:
        rows.append([
            "strict final ready",
            "scripts/replay_full_verified.py",
            "summary",
            fmt_num(full_verified.get("runtime_seconds"), 4),
            full_verified.get("status", ""),
        ])
    return ["tier", "script", "heavy layer", "runtime sec.", "status/returncode"], rows, (
        "Replay protocol tiers and runtime/status fields generated from the Phase-7 replay audit payload."
    ), "tab:replay-protocol-tiers"


