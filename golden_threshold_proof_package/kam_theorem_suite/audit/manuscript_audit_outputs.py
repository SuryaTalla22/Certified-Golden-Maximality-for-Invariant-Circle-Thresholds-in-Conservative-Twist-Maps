def load_sources(root: Path = Path(".")) -> dict[str, Any]:
    sources: dict[str, Any] = {}
    missing = []
    for key, rel in DEFAULT_SOURCE_PATHS.items():
        path = root / rel
        if not path.exists():
            missing.append(str(rel))
        else:
            sources[key] = read_json(path)
    if missing:
        raise FileNotFoundError("Missing proof-audit source payloads: " + "; ".join(missing))
    return sources


def generate_manuscript_tables(root: Path = Path(".")) -> dict[str, Any]:
    sources = load_sources(root)
    table_specs = {
        "lower_corridor_segments": build_lower_table(sources["lower"]),
        "upper_obstruction_margin": build_upper_table(sources["upper"]),
        "transport_budget": build_transport_table(sources["transport"]),
        "domain_grammar_counts": build_domain_table(sources["domain"]),
        "replay_protocol": build_replay_table(sources["replay"], sources["full_verified"]),
    }
    outputs = []
    for key, spec in table_specs.items():
        path = root / EXPECTED_TABLES[key]
        write_table(path, *spec)
        outputs.append(path)
    return build_manifest(root, table_outputs=outputs, figure_outputs=[])


