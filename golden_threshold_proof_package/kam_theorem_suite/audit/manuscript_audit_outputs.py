def _pdf_escape_text(text: Any) -> str:
    s = str(text)
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


@dataclass
class MiniPDF:
    width: int = 612
    height: int = 792
    content: list[str] | None = None

    def __post_init__(self) -> None:
        if self.content is None:
            self.content = []

    def line(self, x1: float, y1: float, x2: float, y2: float, width: float = 1.0) -> None:
        self.content.append(f"{width:.3f} w {x1:.3f} {y1:.3f} m {x2:.3f} {y2:.3f} l S")

    def rect(self, x: float, y: float, w: float, h: float, gray: float = 0.85, stroke: bool = False) -> None:
        gray = max(0.0, min(1.0, gray))
        op = "B" if stroke else "f"
        self.content.append(f"{gray:.3f} g {x:.3f} {y:.3f} {w:.3f} {h:.3f} re {op} 0 g")

    def text(self, x: float, y: float, text: Any, size: int = 9, align: str = "left") -> None:
        escaped = _pdf_escape_text(text)
        # Approximate centering/right alignment using glyph-count width.
        adj = 0.0
        if align == "center":
            adj = -0.5 * len(str(text)) * size * 0.48
        elif align == "right":
            adj = -len(str(text)) * size * 0.48
        self.content.append(f"BT /F1 {size} Tf {x + adj:.3f} {y:.3f} Td ({escaped}) Tj ET")

    def write(self, path: Path) -> None:
        ensure_parent(path)
        stream = "\n".join(self.content or []) + "\n"
        objs: list[bytes] = []
        objs.append(b"<< /Type /Catalog /Pages 2 0 R >>")
        objs.append(b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>")
        page = f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {self.width} {self.height}] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>".encode()
        objs.append(page)
        objs.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
        stream_b = stream.encode("latin-1", errors="replace")
        objs.append(b"<< /Length " + str(len(stream_b)).encode() + b" >>\nstream\n" + stream_b + b"endstream")
        pdf = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
        offsets = [0]
        for i, obj in enumerate(objs, 1):
            offsets.append(len(pdf))
            pdf += f"{i} 0 obj\n".encode() + obj + b"\nendobj\n"
        xref_pos = len(pdf)
        pdf += f"xref\n0 {len(objs)+1}\n".encode()
        pdf += b"0000000000 65535 f \n"
        for off in offsets[1:]:
            pdf += f"{off:010d} 00000 n \n".encode()
        pdf += f"trailer << /Size {len(objs)+1} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode()
        path.write_bytes(bytes(pdf))


def draw_bar_chart(path: Path, title: str, labels: Sequence[str], values: Sequence[float], *, subtitle: str = "", y_label: str = "", value_format: str = "{:.2e}") -> None:
    pdf = MiniPDF()
    left, bottom, width, height = 78, 155, 455, 420
    values = [float(v) for v in values]
    max_val = max([abs(v) for v in values] + [1.0])
    if max_val <= 0:
        max_val = 1.0
    pdf.text(306, 742, title, size=15, align="center")
    if subtitle:
        pdf.text(306, 722, subtitle, size=9, align="center")
    pdf.line(left, bottom, left, bottom + height, 0.8)
    pdf.line(left, bottom, left + width, bottom, 0.8)
    for i in range(6):
        y = bottom + height * i / 5
        pdf.line(left - 4, y, left + width, y, 0.25)
        pdf.text(left - 8, y - 3, value_format.format(max_val * i / 5), size=7, align="right")
    n = max(1, len(values))
    slot = width / n
    bar_w = min(46, slot * 0.62)
    for i, (label, val) in enumerate(zip(labels, values)):
        x = left + slot * i + (slot - bar_w) / 2
        h = 0 if max_val == 0 else height * max(0, val) / max_val
        gray = 0.82 - 0.18 * (i % 3) / 2
        pdf.rect(x, bottom, bar_w, h, gray=gray, stroke=True)
        pdf.text(x + bar_w / 2, bottom + h + 9, value_format.format(val), size=7, align="center")
        short_label = str(label)
        if len(short_label) > 20:
            short_label = short_label[:17] + "..."
        pdf.text(x + bar_w / 2, bottom - 20, short_label, size=7, align="center")
    if y_label:
        pdf.text(35, bottom + height / 2, y_label, size=8, align="center")
    pdf.text(306, 92, "Generated from proof-audit JSON/CSV payloads; not manually typed.", size=8, align="center")
    pdf.write(path)


def draw_waterfall(path: Path, title: str, components: Sequence[tuple[str, float]], available_gap: float, remaining_margin: float) -> None:
    labels = [name for name, _ in components] + ["remaining"]
    values = [value for _, value in components] + [remaining_margin]
    pdf = MiniPDF()
    left, bottom, width, height = 78, 150, 455, 420
    max_val = max(available_gap, sum(max(0, v) for v in values), 1e-12)
    pdf.text(306, 742, title, size=15, align="center")
    pdf.text(306, 722, f"available gap = {available_gap:.3e}; remaining margin = {remaining_margin:.3e}", size=9, align="center")
    pdf.line(left, bottom, left, bottom + height, 0.8)
    pdf.line(left, bottom, left + width, bottom, 0.8)
    pdf.line(left, bottom + height * available_gap / max_val, left + width, bottom + height * available_gap / max_val, 1.2)
    pdf.text(left + width + 8, bottom + height * available_gap / max_val - 3, "available", size=8)
    n = max(1, len(values))
    slot = width / n
    bar_w = min(45, slot * 0.58)
    for i, (label, val) in enumerate(zip(labels, values)):
        x = left + slot * i + (slot - bar_w) / 2
        h = height * max(0, val) / max_val
        pdf.rect(x, bottom, bar_w, h, gray=0.78 if label != "remaining" else 0.62, stroke=True)
        pdf.text(x + bar_w / 2, bottom + h + 9, f"{val:.2e}", size=7, align="center")
        pdf.text(x + bar_w / 2, bottom - 20, label, size=7, align="center")
    pdf.text(306, 92, "Transport pass condition: available gap exceeds the total charged budget.", size=8, align="center")
    pdf.write(path)


def draw_protocol_tiers(path: Path, replay: Mapping[str, Any], full_verified: Mapping[str, Any] | None) -> None:
    order = ["minimal", "downstream", "artifact_audit_suite", "heavy_lower", "heavy_upper", "full_verified"]
    pdf = MiniPDF()
    pdf.text(306, 742, "Replay protocol tiers", size=15, align="center")
    status = full_verified.get("status") if full_verified else "unknown"
    strict = full_verified.get("strict_final_ready") if full_verified else False
    pdf.text(306, 722, f"full verified status: {status}; strict_final_ready={strict}", size=9, align="center")
    x0, y0 = 75, 590
    box_w, box_h, gap = 160, 56, 24
    for i, key in enumerate(order):
        row = i // 3
        col = i % 3
        x = x0 + col * (box_w + gap)
        y = y0 - row * 145
        entry = replay.get(key, {})
        gray = 0.70 if entry.get("heavy_layer") else 0.88
        pdf.rect(x, y, box_w, box_h, gray=gray, stroke=True)
        pdf.text(x + box_w / 2, y + 35, key, size=10, align="center")
        runtime = entry.get("runtime_seconds", 0)
        pdf.text(x + box_w / 2, y + 18, f"runtime {fmt_num(runtime, 3)} sec", size=7, align="center")
        pdf.text(x + box_w / 2, y + 6, "heavy" if entry.get("heavy_layer") else "lightweight", size=7, align="center")
        if i < len(order) - 1 and col != 2:
            pdf.line(x + box_w, y + box_h / 2, x + box_w + gap, y + box_h / 2, 0.8)
    pdf.text(306, 250, "Known lower-anchor gap is preserved as a fail-closed strict-readiness blocker.", size=8, align="center")
    pdf.write(path)


