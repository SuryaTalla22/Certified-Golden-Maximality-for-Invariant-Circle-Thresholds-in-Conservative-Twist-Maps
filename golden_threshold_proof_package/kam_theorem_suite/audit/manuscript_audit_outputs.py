def build_manifest(root: Path, table_outputs: Sequence[Path] | None = None, figure_outputs: Sequence[Path] | None = None) -> dict[str, Any]:
    table_outputs = list(table_outputs or [])
    figure_outputs = list(figure_outputs or [])
    source_entries = []
    for key, rel in DEFAULT_SOURCE_PATHS.items():
        path = root / rel
        if path.exists():
            source_entries.append({"key": key, "path": str(rel), "sha256": sha256_file(path), "bytes": path.stat().st_size})
    output_paths = list(table_outputs) + list(figure_outputs)
    output_entries = []
    for path in output_paths:
        if path.exists():
            output_entries.append({"path": str(path.relative_to(root)), "sha256": sha256_file(path), "bytes": path.stat().st_size})
    # If a manifest already exists, merge outputs so table-only and figure-only runs accumulate.
    manifest_file = root / MANIFEST_PATH
    existing_outputs: dict[str, dict[str, Any]] = {}
    if manifest_file.exists():
        try:
            old = read_json(manifest_file)
            for entry in old.get("outputs", []):
                existing_outputs[entry.get("path", "")] = entry
        except Exception:
            pass
    for entry in output_entries:
        existing_outputs[entry["path"]] = entry
    lower_status = None
    known_lower_gap = None
    try:
        lower = read_json(root / DEFAULT_SOURCE_PATHS["lower"])
        lower_status = lower.get("status")
        known_lower_gap = not bool(lower.get("final_anchor_reached"))
    except Exception:
        pass
    manifest = {
        "schema": "phase10_manuscript_audit_outputs_v1",
        "status": "passed-with-known-lower-gap" if known_lower_gap else "passed",
        "known_lower_gap": bool(known_lower_gap),
        "lower_status": lower_status,
        "source_payloads": source_entries,
        "outputs": [existing_outputs[k] for k in sorted(existing_outputs)],
        "expected_tables": {k: str(v) for k, v in EXPECTED_TABLES.items()},
        "expected_figures": {k: str(v) for k, v in EXPECTED_FIGURES.items()},
        "manual_editing_allowed": False,
        "generation_principle": "All manuscript tables and figures are generated directly from proof-audit JSON/CSV payloads.",
    }
    write_json(manifest_file, manifest)
    return manifest


def generate_all_manuscript_outputs(root: Path = Path(".")) -> dict[str, Any]:
    generate_manuscript_tables(root)
    generate_manuscript_figures(root)
    return build_manifest(root, [root / p for p in EXPECTED_TABLES.values()], [root / p for p in EXPECTED_FIGURES.values()])


def cli_tables(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate manuscript audit LaTeX tables from proof-audit JSON payloads.")
    parser.add_argument("--root", default=".", help="Repository root")
    parser.add_argument("--strict", action="store_true", help="Fail if any expected table is missing after generation")
    args = parser.parse_args(argv)
    root = Path(args.root)
    manifest = generate_manuscript_tables(root)
    missing = [str(p) for p in EXPECTED_TABLES.values() if not (root / p).exists()]
    if args.strict and missing:
        raise SystemExit("Missing expected tables: " + "; ".join(missing))
    print(json.dumps({"status": manifest["status"], "generated_tables": len(EXPECTED_TABLES), "missing": missing}, indent=2))
    return 0 if not missing else 1


